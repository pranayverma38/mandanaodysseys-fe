import type { DestinationCityTemperature, DestinationMonthlyTemperature } from './types'

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'] as const

/** Build monthly rows from compact [high, low, rainfall mm] tuples. */
function climate(data: [high: number, low: number, rain: number][]): DestinationMonthlyTemperature[] {
  return data.map(([avgHighC, avgLowC, rainfallMm], index) => ({
    month: MONTHS[index],
    avgHighC,
    avgLowC,
    rainfallMm,
  }))
}

